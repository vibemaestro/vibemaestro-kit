#!/bin/bash
# =============================================================================
# An English-only consumer repo: `language`, the spec check, the init scaffold and the PR body from tokens, the evidence fence
# =============================================================================
# Run: bash tests/test-language.sh
#
# Families:
#   [spec]   `"language": "en"`: an English spec passes, the same spec without `## Goal` (or with a section left Vietnamese) is
#            refused; no config: a Vietnamese spec passes and the English one is refused; a file key still wins over the preset
#   [fence]  evidence holding triple and quadruple backtick fences, a `## ` line, a line of five backticks and tildes is one code block
#   [novi]   under `en`, the PR bodies and every file `kb.py init --lang en` and `kb.py new` write hold no Vietnamese letter
#            (positive control: the `vi` bodies and scaffold do)
#   [vibyte] no config (PR bodies) and `init --lang vi`: the PR bodies, the init scaffold and the `kb.py new` templates equal, byte for byte, what plugin 2.1.0
#            wrote (tests/fixtures/language/vi, generated by the code before this change); new-plan.md is the multi-PR plan
#            template of sdlc 2.24.0, changed on purpose for multi-PR plans; new-spec.md and README.md carry the
#            `## Inputs and failure cases` section, added on purpose
#   [init]   `--lang` records `language` in a new config, plain init records `en`; an existing config is never rewritten, so
#            a `--lang` that differs from its language is rc 64 with nothing written, and a matching one prints `would add`; a
#            config that already says `en` gives the English scaffold; `--lang fr` is rc 64
#   [msgs]   under `en`, what `kb.py new`, `check spec` (pass and fail) and `check current-state` print, and the lines
#            the open-pr current-state gate prints, hold no Vietnamese letter
#   [config] `language` and the new tokens are validated: an unknown language, `evidence_cut` without `{n}`, an empty spec token,
#            a placeholder that does not start with `<` or holds `>`
#
# Every family runs on a copy of the real plugin. Real git on throw-away repositories, no gh, the network shims of
# netguard.sh, no model, no network. Prose of messages is never asserted, only exit codes, files and the words the spec names.
# =============================================================================
set -uo pipefail
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
SRC_ROOT=$(CDPATH= cd -- "$HERE/.." && pwd)
# shellcheck source=fixtures/lib.sh
. "$HERE/fixtures/lib.sh"
# shellcheck source=fixtures/ports.sh
. "$HERE/fixtures/ports.sh"

PLUGIN="$SRC_ROOT/plugins/vibemaestro-sdlc"
FX="$HERE/fixtures/language"
LANGPY="$FX/lang.py"
TMP=$(mktemp -d); TMP=$(cd "$TMP" && pwd -P)
trap 'rm -rf "$TMP"' EXIT
clean_env "$TMP"

PLX=""

# ── helpers ──────────────────────────────────────────────────────────────────────────────────────
mk_repo() { local d; d=$(fresh); git_ init -q -b main "$d"; printf '%s' "$d"; }
# set_cfg <repo> <json> — write the repo's config
set_cfg() { mkdir -p "$1/.vibemaestro"; printf '%s\n' "$2" > "$1/.vibemaestro/sdlc.json"; }
kb() { local d=$1; shift; (cd "$d" && cenv python3 -B "$PLX/scripts/kb.py" "$@" 2>&1); }
rc_of() { local d=$1; shift; (cd "$d" && cenv python3 -B "$PLX/scripts/kb.py" "$@" >/dev/null 2>&1); echo $?; }
lang() { cenv python3 -B "$LANGPY" "$@"; }
# en_spec <file> [skip heading] — a filled English spec; the section named by the second argument is left out
en_spec() {
  local skip=${2:-}
  { printf -- '---\ndescription: "An English spec"\n---\n\n# Example\n\nIntent: kb/intent/2026-01-01-example.md\n\n'
    [ "$skip" = Context ] || printf '## Context\n\nWhy.\n\n'
    [ "$skip" = Goal ] || printf '## Goal\n\nWhat.\n\n'
    [ "$skip" = "Out of scope" ] || printf '## Out of scope\n\nNone.\n\n'
    printf '## Acceptance criteria\n\n1. `make test` → 0 fail\n2. The PR has a `## Run evidence` section with the real output.\n'
  } > "$1"
}
EN='{"schema": 1, "language": "en"}'

# ── [spec] ───────────────────────────────────────────────────────────────────────────────────────
fam_spec() {
  PLX=$1; local R V
  R=$(mk_repo); set_cfg "$R" "$EN"; mkdir -p "$R/kb/specs"
  en_spec "$R/kb/specs/2026-01-01-ok.md"
  eq "$(rc_of "$R" check spec 2026-01-01-ok)" 0 "[spec] en: an English spec passes (rc 0)"
  en_spec "$R/kb/specs/2026-01-01-nogoal.md" Goal
  eq "$(rc_of "$R" check spec 2026-01-01-nogoal)" 65 "[spec] en: the spec without ## Goal is refused (rc 65)"
  has "$(kb "$R" check spec 2026-01-01-nogoal)" "## Goal" "[spec] en: …and the refusal names ## Goal"
  en_spec "$R/kb/specs/2026-01-01-noctx.md" Context
  eq "$(rc_of "$R" check spec 2026-01-01-noctx)" 65 "[spec] en: the spec without ## Context is refused (rc 65)"
  sed 's/^## Out of scope$/## Ngoài phạm vi/' "$R/kb/specs/2026-01-01-ok.md" > "$R/kb/specs/2026-01-01-mixed.md"
  eq "$(rc_of "$R" check spec 2026-01-01-mixed)" 65 "[spec] en: a section left in Vietnamese is refused (rc 65)"
  sed 's/Run evidence/Bằng chứng chạy/' "$R/kb/specs/2026-01-01-ok.md" > "$R/kb/specs/2026-01-01-vievidence.md"
  eq "$(rc_of "$R" check spec 2026-01-01-vievidence)" 65 "[spec] en: a last criterion naming the Vietnamese evidence heading is refused"
  # `kb.py new spec` under en: the template carries the English names and the English placeholder, and refuses until filled
  kb "$R" new spec fresh --date 2026-01-02 >/dev/null
  has "$(cat "$R/kb/specs/2026-01-02-fresh.md")" "## Goal" "[spec] en: kb.py new spec writes ## Goal"
  eq "$(rc_of "$R" check spec 2026-01-02-fresh)" 65 "[spec] en: the new template is refused while it holds <FILL"
  python3 -c 'import re,sys; p=sys.argv[1]; t=open(p).read(); t=re.sub(r"<FILL: [^>]*>", "filled", t); t=t.replace("`filled`", "`make test`"); open(p,"w").write(t)' "$R/kb/specs/2026-01-02-fresh.md"
  eq "$(rc_of "$R" check spec 2026-01-02-fresh)" 0 "[spec] en: the new template, filled, passes"
  # a spec written before the switch to en still has Vietnamese blanks: they count too
  sed 's/^Why\.$/<ĐIỀN: why>/' "$R/kb/specs/2026-01-01-ok.md" > "$R/kb/specs/2026-01-01-oldblank.md"
  eq "$(rc_of "$R" check spec 2026-01-01-oldblank)" 65 "[spec] en: a blank of the other language (<ĐIỀN) is refused"
  # a file key wins over the preset
  set_cfg "$R" '{"schema": 1, "language": "en", "tokens": {"spec": {"goal": "Objective"}}}'
  eq "$(rc_of "$R" check spec 2026-01-01-ok)" 65 "[spec] en + tokens.spec.goal: Objective: ## Goal no longer counts"
  sed 's/^## Goal$/## Objective/' "$R/kb/specs/2026-01-01-ok.md" > "$R/kb/specs/2026-01-01-obj.md"
  eq "$(rc_of "$R" check spec 2026-01-01-obj)" 0 "[spec] en + tokens.spec.goal: Objective: ## Objective passes"
  # no config: Vietnamese passes, English is refused
  V=$(mk_repo); mkdir -p "$V/kb/specs"; cp "$FX/vi/new-spec.md" "$V/kb/specs/2026-01-01-vi.md"
  python3 -c 'import re,sys; p=sys.argv[1]; t=open(p).read(); t=re.sub(r"<ĐIỀN: [^>]*>", "điền", t); t=t.replace("`điền`", "`make test`"); open(p,"w").write(t)' "$V/kb/specs/2026-01-01-vi.md"
  eq "$(rc_of "$V" check spec 2026-01-01-vi)" 0 "[spec] no config: a filled Vietnamese spec passes (rc 0)"
  cp "$R/kb/specs/2026-01-01-ok.md" "$V/kb/specs/2026-01-01-en.md"
  eq "$(rc_of "$V" check spec 2026-01-01-en)" 65 "[spec] no config: the English spec is refused (rc 65)"
  set_cfg "$V" '{"schema": 1, "language": "vi"}'
  eq "$(rc_of "$V" check spec 2026-01-01-vi)" 0 "[spec] language: vi: the Vietnamese spec passes"
}

# ── [fence] ──────────────────────────────────────────────────────────────────────────────────────
fam_fence() {
  PLX=$1; local R O m
  for cfg in none en; do
    R=$(mk_repo); [ "$cfg" = en ] && set_cfg "$R" "$EN"
    O=$(fresh); lang bodies "$PLX/scripts" "$R" "$O" || bad "[fence] $cfg: bodies built"
    m=$(lang fences "$O/body-fences.md" "$O/evidence-fences.txt"); eq "$?" 0 "[fence] $cfg: evidence with triple and quadruple fences is one code block ($m)"
    has "$(cat "$O/body-fences.md")" $'\n``````\n$ cat report.md' "[fence] $cfg: the fence is one backtick longer than the longest run (5)"
    has "$(cat "$O/body-plain.md")" $'\n```\n$ make test\nok\n```' "[fence] $cfg: evidence without backticks keeps the three-backtick fence"
  done
}

# ── [novi] ───────────────────────────────────────────────────────────────────────────────────────
fam_novi() {
  PLX=$1; local R O V f
  R=$(mk_repo); set_cfg "$R" "$EN"; set_cfg "$R" '{"schema": 1, "language": "en", "pr": {"tester_exempt": {"decision": "kb/decisions/no-e2e.md"}}}'
  mkdir -p "$R/kb/decisions"; : > "$R/kb/decisions/no-e2e.md"
  O=$(fresh); lang bodies "$PLX/scripts" "$R" "$O" || bad "[novi] bodies built"
  for f in plain long notrun fences; do
    lang viet "$O/body-$f.md" >/dev/null; eq "$?" 0 "[novi] en: body-$f has no Vietnamese letter ($(lang viet "$O/body-$f.md" | cut -d' ' -f1))"
  done
  has "$(cat "$O/body-long.md")" "(40 lines cut from the middle)" "[novi] en: the long evidence is cut with the English marker"
  has "$(cat "$O/body-notrun.md")" "**Not run**" "[novi] en: the not-run warning is English"
  has "$(cat "$O/body-long.md")" "Patch for #98" "[novi] en: the fixes line"
  # the scaffold: init --lang en, then new intent/plan/spec
  R=$(mk_repo); kb "$R" init --lang en >/dev/null
  kb "$R" new intent i --date 2026-01-01 >/dev/null; kb "$R" new plan p --date 2026-01-01 >/dev/null; kb "$R" new spec s --date 2026-01-01 >/dev/null
  for f in kb/README.md kb/current-state.md kb/intent/2026-01-01-i.md kb/plans/2026-01-01-p.md kb/specs/2026-01-01-s.md .vibemaestro/sdlc.json .vibemaestro/rules/README.md .vibemaestro/rules/example.instructions.md; do
    lang viet "$R/$f" >/dev/null; eq "$?" 0 "[novi] en: $f has no Vietnamese letter ($(lang viet "$R/$f" | cut -d' ' -f1))"
  done
  # positive control: the detector sees the Vietnamese defaults
  V=$(mk_repo); O=$(fresh); lang bodies "$PLX/scripts" "$V" "$O" >/dev/null
  lang viet "$O/body-long.md" >/dev/null; eq "$?" 1 "[novi] control: the default (vi) body has Vietnamese letters"
  kb "$V" init --lang vi >/dev/null
  lang viet "$V/kb/README.md" >/dev/null; eq "$?" 1 "[novi] control: the vi README has Vietnamese letters"
}

# ── [msgs] ──────────────────────────────────────────────────────────────────────────────
fam_msgs() {
  PLX=$1; local R O
  R=$(mk_repo); kb "$R" init --lang en >/dev/null
  O="$(fresh)/out.txt"
  { kb "$R" new intent i --date 2026-01-01; kb "$R" new plan p --date 2026-01-01; kb "$R" new spec s --date 2026-01-01
    kb "$R" new spec s --date 2026-01-01
    kb "$R" check spec 2026-01-01-s
    en_spec "$R/kb/specs/2026-01-02-e.md"; kb "$R" check spec 2026-01-02-e
    en_spec "$R/kb/specs/2026-01-03-g.md" Goal; kb "$R" check spec 2026-01-03-g
    kb "$R" check current-state
    (cd "$R" && cenv python3 -B - "$PLX/scripts" <<'PY'
import sys
sys.path.insert(0, sys.argv[1])
import open_pr, sdlc_config
en = {"schema": 1, "language": "en"}
print(open_pr.current_state_gate(".", "main", "HEAD", "", sdlc_config.effective(en), True)[1])
print(open_pr.current_state_gate(".", "main", "HEAD", "", sdlc_config.effective(dict(en, current_state={"gate": "off"})), True)[1])
PY
    )
  } > "$O" 2>&1
  has "$(cat "$O")" "slug for intent-branch.sh" "[msgs] instrument: the output of kb.py new is captured"
  has "$(cat "$O")" "is missing" "[msgs] instrument: …and of a failing spec check"
  has "$(cat "$O")" "passes the current-state shape" "[msgs] instrument: …and of the current-state check"
  has "$(cat "$O")" "the gate does not apply" "[msgs] instrument: …and the open-pr gate lines"
  lang viet "$O" >/dev/null; eq "$?" 0 "[msgs] en: kb.py new, check spec, check current-state and the open-pr gate print no Vietnamese letter ($(lang viet "$O" | cut -d' ' -f1))"
}

# ── [vibyte] ─────────────────────────────────────────────────────────────────────────────────────
fam_vibyte() {
  PLX=$1; local R O f
  R=$(mk_repo); O=$(fresh); lang bodies "$PLX/scripts" "$R" "$O" || bad "[vibyte] bodies built"
  for f in plain long notrun; do
    cmp -s "$O/body-$f.md" "$FX/vi/body-$f.md" && ok "[vibyte] body-$f equals the golden bytes (2.1.0 without the flow section)" || bad "[vibyte] body-$f differs from the golden bytes"
  done
  kb "$R" init --lang vi >/dev/null
  kb "$R" new spec s --date 2026-01-01 >/dev/null; kb "$R" new intent i --date 2026-01-01 >/dev/null; kb "$R" new plan p --date 2026-01-01 >/dev/null
  for f in "README.md kb/README.md" "current-state.md kb/current-state.md" "new-spec.md kb/specs/2026-01-01-s.md" "new-intent.md kb/intent/2026-01-01-i.md" "new-plan.md kb/plans/2026-01-01-p.md"; do
    set -- $f
    cmp -s "$R/$2" "$FX/vi/$1" && ok "[vibyte] $2 equals the 2.1.0 bytes" || bad "[vibyte] $2 differs from the 2.1.0 bytes"
  done
  eq "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("language"))' "$R/.vibemaestro/sdlc.json")" vi "[vibyte] init --lang vi records language: vi"
}

# ── [init] ───────────────────────────────────────────────────────────────────────────────────────
fam_init() {
  PLX=$1; local R out A
  R=$(mk_repo); kb "$R" init --lang en >/dev/null
  eq "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("language"))' "$R/.vibemaestro/sdlc.json")" en "[init] --lang en records language: en in the new config"
  has "$(head -1 "$R/kb/README.md")" "of this repo" "[init] --lang en writes the English README"
  eq "$(rc_of "$R" check current-state)" 0 "[init] the English current-state skeleton passes kb.py check current-state"
  R=$(mk_repo); kb "$R" init >/dev/null
  eq "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("language"))' "$R/.vibemaestro/sdlc.json")" en "[init] plain init records language: en in the new config"
  has "$(head -1 "$R/kb/README.md")" "of this repo" "[init] …and writes the English scaffold"
  R=$(mk_repo); kb "$R" init --lang vi >/dev/null
  eq "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("language"))' "$R/.vibemaestro/sdlc.json")" vi "[init] --lang vi records language: vi in the new config"
  R=$(mk_repo); set_cfg "$R" '{"schema": 1}'; kb "$R" init >/dev/null
  has "$(head -1 "$R/kb/README.md")" "của repo này" "[init] an existing config without language, no --lang: the Vietnamese scaffold (absent stays vi)"
  # an existing config is never rewritten, so the scaffold must speak its language: a --lang that differs is refused
  R=$(mk_repo); set_cfg "$R" '{"schema": 1}'
  eq "$(rc_of "$R" init --lang en)" 64 "[init] an existing config without language (vi), --lang en: rc 64"
  [ -e "$R/kb" ] && bad "[init] …and nothing written (kb/ exists)" || ok "[init] …and nothing written"
  eq "$(cat "$R/.vibemaestro/sdlc.json")" '{"schema": 1}' "[init] …and the config is not rewritten"
  out=$(kb "$R" init --lang vi)
  has "$out" 'would add language = "vi"' "[init] the same config, --lang vi (it matches): would add language"
  has "$(head -1 "$R/kb/README.md")" "của repo này" "[init] …and the Vietnamese scaffold"
  R=$(mk_repo); set_cfg "$R" "$EN"; kb "$R" init >/dev/null
  has "$(head -1 "$R/kb/README.md")" "of this repo" "[init] a config that says en, no --lang: the English scaffold"
  R=$(mk_repo); set_cfg "$R" '{"schema": 1}'; A=$(fresh); printf '{"language": "en"}\n' > "$A/answers.json"
  eq "$(rc_of "$R" init --answers "$A/answers.json")" 64 "[init] an existing vi config, answers language en: rc 64 (same as --lang)"
  [ -e "$R/kb" ] && bad "[init] …answers: nothing written (kb/ exists)" || ok "[init] …answers: nothing written"
  # answers whose spec names collide are refused before the first write (a rule that spans keys, not only the schema)
  R=$(mk_repo); A=$(fresh); printf '{"tokens": {"spec": {"goal": "Context"}}}\n' > "$A/answers.json"
  eq "$(rc_of "$R" init --lang en --answers "$A/answers.json")" 65 "[init] answers with two spec sections of one name: rc 65"
  eq "$(git_ -C "$R" status --porcelain)" "" "[init] …and nothing written before the refusal"
  R=$(mk_repo); eq "$(rc_of "$R" init --lang fr)" 64 "[init] --lang fr: rc 64"
  eq "$(git_ -C "$R" status --porcelain)" "" "[init] …and nothing written"
}

# ── [config] ─────────────────────────────────────────────────────────────────────────────────────
fam_config() {
  PLX=$1; local R
  R=$(mk_repo)
  set_cfg "$R" '{"schema": 1, "language": "fr"}'; eq "$(rc_of "$R" config check)" 65 "[config] language: fr is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"evidence_cut": "cut"}}'; eq "$(rc_of "$R" config check)" 65 "[config] evidence_cut without {n} is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"goal": ""}}}'; eq "$(rc_of "$R" config check)" 65 "[config] an empty tokens.spec.goal is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"nope": "x"}}}'; eq "$(rc_of "$R" config check)" 0 "[config] an unknown tokens.spec key only warns (0, rule config-compat)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"context": ""}}}'; eq "$(rc_of "$R" config check)" 65 "[config] an empty tokens.spec heading is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"placeholder": "TODO"}}}'; eq "$(rc_of "$R" config check)" 65 "[config] a placeholder that does not start with < is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"placeholder": "<TODO>"}}}'; eq "$(rc_of "$R" config check)" 65 "[config] a placeholder that holds > is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"placeholder": "<"}}}'; eq "$(rc_of "$R" config check)" 65 "[config] a lone < as the placeholder is refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"placeholder": "<TODO"}}}'; eq "$(rc_of "$R" config check)" 0 "[config] the placeholder <TODO is accepted"
  set_cfg "$R" '{"schema": 1, "language": "en", "tokens": {"spec": {"goal": "Goal "}}}'; eq "$(rc_of "$R" config check)" 65 "[config] a spec section name with a trailing space is refused (65)"
  set_cfg "$R" '{"schema": 1, "language": "en", "tokens": {"spec": {"goal": "Context"}}}'; eq "$(rc_of "$R" config check)" 65 "[config] two spec sections with one name are refused (65)"
  set_cfg "$R" '{"schema": 1, "tokens": {"spec": {"design": "Mục tiêu"}}}'; eq "$(rc_of "$R" config check)" 65 "[config] …also when the other name comes from the defaults"
  set_cfg "$R" '{"schema": 1, "language": "en", "tokens": {"summary_heading": "Overview"}}'
  eq "$(cd "$R" && cenv python3 -B "$PLX/scripts/sdlc_config.py" get tokens.summary_heading)" Overview "[config] a file token wins over the en preset"
  eq "$(cd "$R" && cenv python3 -B "$PLX/scripts/sdlc_config.py" get tokens.evidence_heading)" "Run evidence" "[config] …and the preset fills the rest"
  eq "$(cd "$R" && cenv python3 -B "$PLX/scripts/sdlc_config.py" get language --default)" vi "[config] the default language is vi"
}

FAMILIES="fam_spec fam_fence fam_novi fam_msgs fam_vibyte fam_init fam_config"
PL0="$TMP/plugin-real"; mk_plugin_copy "$PL0"
for f in README.md current-state.md new-spec.md new-intent.md new-plan.md body-plain.md body-long.md body-notrun.md; do
  [ -s "$FX/vi/$f" ] && ok "instrument: golden $f exists" || bad "instrument: golden $f is missing"
done
for f in $FAMILIES; do echo "-- $f"; "$f" "$PL0"; done

echo
summary
